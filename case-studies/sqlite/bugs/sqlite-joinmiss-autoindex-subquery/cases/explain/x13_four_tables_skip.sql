CREATE TABLE t0(x INT);
CREATE TABLE t1(a INT, b INT);
CREATE TABLE t3(k INTEGER PRIMARY KEY);
CREATE TABLE ty(y INT, c INT);
CREATE TABLE ins(y INT); CREATE TABLE log(y INT, n INT);
CREATE TRIGGER tr AFTER INSERT ON ins BEGIN
  INSERT INTO log SELECT new.y, count(*) FROM t0 CROSS JOIN t1 CROSS JOIN t3 WHERE t1.a=t0.x AND t3.k=t1.b+new.y;
END;
CREATE TABLE t2(c INT); EXPLAIN SELECT count(*) FROM t0 CROSS JOIN t1 CROSS JOIN t2 CROSS JOIN t3 WHERE t1.a=t0.x AND t3.k=t1.b;
