(* Standalone ppxlib driver with bisect_ppx linked in, plus an optional
   location remapper used for files generated by tools/cvt_emit from .mlp:
   -cov-remap-mlp <orig.mlp> maps every position (line L, column C) of the
   generated .ml to (line L, min C len(L)) of the original .mlp, and sets the
   file name.  cvt_emit preserves line structure, so lines match exactly. *)

let remap_file = ref None

let line_starts file =
  let ic = open_in_bin file in
  let s = really_input_string ic (in_channel_length ic) in
  close_in ic;
  let starts = ref [0] in
  String.iteri (fun i c -> if c = '\n' then starts := (i + 1) :: !starts) s;
  let a = Array.of_list (List.rev !starts) in
  a, String.length s

let remap_impl st =
  match !remap_file with
  | None -> st
  | Some file ->
    let starts, len = line_starts file in
    let nlines = Array.length starts in
    let map_pos (p : Lexing.position) : Lexing.position =
      if p.pos_cnum < 0 then p else begin
        let l = p.pos_lnum in
        if l < 1 || l > nlines then
          { p with pos_fname = file; pos_cnum = len; pos_bol = len }
        else begin
          let bol = starts.(l - 1) in
          let eol = if l < nlines then starts.(l) - 1 else len in
          let col = max 0 (p.pos_cnum - p.pos_bol) in
          { p with pos_fname = file; pos_bol = bol;
                   pos_cnum = min (bol + col) eol }
        end
      end
    in
    let m = object
      inherit Ppxlib.Ast_traverse.map
      method! position p = map_pos p
    end in
    m#structure st

let () =
  Ppxlib.Driver.add_arg "-cov-remap-mlp"
    (Arg.String (fun s -> remap_file := Some s))
    ~doc:"<file.mlp> Remap locations to original .mlp file (cvt_emit output)";
  Ppxlib.Driver.register_transformation ~preprocess_impl:remap_impl "cov_remap_mlp";
  Ppxlib.Driver.standalone ()
