CREATE TABLE p_hi PARTITION OF p FOR VALUES FROM (500) TO (MAXVALUE);
ALTER TABLE p ADD FOREIGN KEY (r) REFERENCES p (k) ON UPDATE CASCADE;
INSERT INTO p VALUES (1, 1);
