\set ON_ERROR_STOP 0
CREATE TABLE p (k int PRIMARY KEY);
CREATE TABLE fk  (f int CONSTRAINT fk_f REFERENCES p DEFERRABLE INITIALLY IMMEDIATE);
CREATE TABLE fkd (f int CONSTRAINT fkd_f REFERENCES p DEFERRABLE INITIALLY DEFERRED);
CREATE TABLE u (k int CONSTRAINT u_k UNIQUE DEFERRABLE INITIALLY IMMEDIATE);
CREATE TABLE x (k int, CONSTRAINT x_k EXCLUDE (k WITH =) DEFERRABLE INITIALLY IMMEDIATE);
INSERT INTO u VALUES (1); INSERT INTO x VALUES (1);

\echo ==== A1 ALL DEFERRED, depth 2, RELEASE s1, ROLLBACK TO s0 (expect ERROR at insert)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS ALL DEFERRED; RELEASE s1; ROLLBACK TO s0;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== A2 by name fk_f DEFERRED, depth 2 (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS fk_f DEFERRED; RELEASE s1; ROLLBACK TO s0;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== A3 control: SET directly in s0, ROLLBACK TO s0 (expect ERROR)
BEGIN; SAVEPOINT s0; SET CONSTRAINTS ALL DEFERRED; ROLLBACK TO s0;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== A4 control: SET in s1, ROLLBACK TO s1 (not released) (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS ALL DEFERRED; ROLLBACK TO s1;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== A5 control: s0 ran its own SET first, then s1 SET+RELEASE, ROLLBACK TO s0 (expect ERROR)
BEGIN; SAVEPOINT s0; SET CONSTRAINTS ALL IMMEDIATE; SAVEPOINT s1; SET CONSTRAINTS ALL DEFERRED; RELEASE s1; ROLLBACK TO s0;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== A6 control: SET in s1, RELEASE s1, no rollback (expect no error, deferred)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS ALL DEFERRED; RELEASE s1;
INSERT INTO fk VALUES (99); ROLLBACK;

\echo ==== B1 INITIALLY DEFERRED set ALL IMMEDIATE in released s1, ROLLBACK TO s0 (expect no error: deferred)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS ALL IMMEDIATE; RELEASE s1; ROLLBACK TO s0;
INSERT INTO fkd VALUES (99); ROLLBACK;
\echo ==== B2 same by name fkd_f IMMEDIATE (expect no error)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS fkd_f IMMEDIATE; RELEASE s1; ROLLBACK TO s0;
INSERT INTO fkd VALUES (99); ROLLBACK;
\echo ==== B3 control: IMMEDIATE directly in s0, ROLLBACK TO s0 (expect no error)
BEGIN; SAVEPOINT s0; SET CONSTRAINTS ALL IMMEDIATE; ROLLBACK TO s0;
INSERT INTO fkd VALUES (99); ROLLBACK;

\echo ==== C1 depth 3: SET in s2, RELEASE s2, RELEASE s1, ROLLBACK TO s0 (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SAVEPOINT s2; SET CONSTRAINTS ALL DEFERRED; RELEASE s2; RELEASE s1; ROLLBACK TO s0;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== C2 depth 3: SET in s2, RELEASE s2, ROLLBACK TO s1 (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SAVEPOINT s2; SET CONSTRAINTS ALL DEFERRED; RELEASE s2; ROLLBACK TO s1;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== C3 depth 3: SET in s2, RELEASE s2, ROLLBACK TO s0 (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SAVEPOINT s2; SET CONSTRAINTS ALL DEFERRED; RELEASE s2; ROLLBACK TO s0;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== C4 depth 3: SET in s2, RELEASE s1 (releases s2 too), ROLLBACK TO s0 (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SAVEPOINT s2; SET CONSTRAINTS ALL DEFERRED; RELEASE s1; ROLLBACK TO s0;
INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== C5 depth 1: SAVEPOINT s1; SET; RELEASE s1; then ROLLBACK whole txn; new txn insert (expect ERROR)
BEGIN; SAVEPOINT s1; SET CONSTRAINTS ALL DEFERRED; RELEASE s1; ROLLBACK;
BEGIN; INSERT INTO fk VALUES (99); ROLLBACK;
\echo ==== C6 depth 2 then whole ROLLBACK; new txn insert (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS ALL DEFERRED; RELEASE s1; ROLLBACK;
BEGIN; INSERT INTO fk VALUES (99); ROLLBACK;

\echo ==== E1 deferrable UNIQUE, ALL DEFERRED in released s1, ROLLBACK TO s0, dup insert (expect ERROR)
BEGIN; SAVEPOINT s0; SAVEPOINT s1; SET CONSTRAINTS ALL DEFERRED; RELEASE s1; ROLLBACK TO s0;
INSERT INTO u VALUES (1); ROLLBACK;
