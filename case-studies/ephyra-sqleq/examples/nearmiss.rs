//! Near-miss pairs end to end: per seed, every anti-rule application
//! (`ephyra_sqleq::antirules`), plain and disguised (an e-graph variant of
//! it: sound rewrites elsewhere, so the pair differs widely in syntax and
//! in one place in meaning); a PostgreSQL witness for each
//! (`ephyra_sqleq::witness`); then sqleq's tools.
//!
//! `cargo run --release --example nearmiss -- <first seed> <count> <out dir> [threads]`
//!
//! Prints the cross-tab and, per rule: pairs, witnessed, proved while
//! witnessed (an unsound proof), proved without a witness (likely equivalent
//! here), fuzz-missed (witnessed, sqleq-fuzz found nothing).

use std::collections::BTreeMap;

use ephyra_sqleq::{
    antirules,
    check::{self, Pair},
    ddl, inputs, variants, witness,
};

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let (first, count): (u64, u64) = (args[1].parse().unwrap(), args[2].parse().unwrap());
    let out = std::path::PathBuf::from(&args[3]);
    let threads: usize = args.get(4).and_then(|s| s.parse().ok()).unwrap_or(8);
    let start = std::time::Instant::now();
    let mut pairs = Vec::new();
    let mut witnessed_by: BTreeMap<String, String> = BTreeMap::new();
    for s in first..first + count {
        let input = inputs::input(s);
        for (k, (q, _)) in input.seeds.iter().enumerate() {
            let mut named: Vec<(String, ephyra_postgresql::expr::Query)> = Vec::new();
            for (j, (rule, v)) in antirules::anti(q, &input.schema).into_iter().enumerate() {
                if let Some(d) = variants::variants(&v, &input.schema, 1, 30, s ^ j as u64).0.into_iter().next() {
                    named.push((format!("s{s}_q{k}_{rule}-d_{j}"), d));
                }
                named.push((format!("s{s}_q{k}_{rule}_{j}"), v));
            }
            let vs: Vec<_> = named.iter().map(|(_, v)| v.clone()).collect();
            let ws = witness::witnesses(&input.case, &input.model, q, &vs).unwrap_or_else(|_| vec![None; vs.len()]);
            for ((name, v), w) in named.into_iter().zip(ws) {
                if let Some(p) = &w {
                    witnessed_by.insert(name.clone(), if p.is_empty() { "(case data)".into() } else { p.clone() });
                }
                pairs.push(Pair { name: name.clone(), file_text: ddl::pair_file(&input.model, &q.sql(), &v.sql(), &format!("near miss {name}; witness: {}", w.as_deref().map_or("none", |p| if p.is_empty() { "case data" } else { p }))), equivalent: false, pg_refutes: w.map(|_| true) });
            }
        }
    }
    let generated = start.elapsed().as_secs_f64();
    let mut rows = check::check(pairs, &out, threads);
    // Pairs a prover proved with no witness yet: search deeper (pairs of
    // perturbations); a witness found now makes the proof unsound.
    let mut deep = 0;
    for r in rows.iter_mut().filter(|r| r.proved() && r.pg_refutes.is_none()) {
        let p: Vec<&str> = r.name.split('_').collect();
        let (s, k): (u64, usize) = (p[0][1..].parse().unwrap(), p[1][1..].parse().unwrap());
        let input = inputs::input(s);
        let seed = &input.seeds[k].0;
        let text = std::fs::read_to_string(&r.file).unwrap_or_default();
        let b_sql = text.lines().filter(|l| !l.starts_with("--") && !l.starts_with("CREATE")).nth(1).unwrap_or("").trim_end_matches(';').to_string();
        // The variant, regenerated by name (same order as above).
        let j: usize = p[p.len() - 1].parse().unwrap();
        let disguised = p[p.len() - 2].ends_with("-d");
        let (_, v) = antirules::anti(seed, &input.schema).into_iter().nth(j).unwrap();
        let v = if disguised { variants::variants(&v, &input.schema, 1, 30, s ^ j as u64).0.into_iter().next().unwrap_or(v) } else { v };
        assert_eq!(v.sql(), b_sql, "regenerated {}", r.name);
        deep += 1;
        if let Ok(Some(w)) = witness::deep_witness(&input.case, &input.model, seed, &v, 400) {
            witnessed_by.insert(r.name.clone(), w);
            r.pg_refutes = Some(true);
        }
    }
    println!("deep witness search on {deep} proved, unwitnessed pairs");
    std::fs::write(out.join("results.tsv"), check::tsv(&rows)).unwrap();
    std::fs::write(out.join("witnesses.tsv"), witnessed_by.iter().map(|(n, p)| format!("{n}\t{p}\n")).collect::<String>()).unwrap();
    print!("{}", check::report(&rows));
    let mut by: BTreeMap<String, [usize; 5]> = BTreeMap::new();
    for r in &rows {
        let p: Vec<&str> = r.name.split('_').collect();
        let rule = p[2..p.len() - 1].join("_").trim_end_matches("-d").to_string();
        let e = by.entry(rule).or_default();
        let w = r.pg_refutes == Some(true);
        e[0] += 1;
        e[1] += usize::from(w);
        e[2] += usize::from(w && r.proved());
        e[3] += usize::from(!w && r.proved());
        e[4] += usize::from(r.finding() == Some("fuzz-missed"));
    }
    println!("{:22} {:>6} {:>9} {:>16} {:>17} {:>11}", "rule", "pairs", "witnessed", "PROVED+witnessed", "proved, no witness", "fuzz-missed");
    for (r, e) in by {
        println!("{r:22} {:>6} {:>9} {:>16} {:>17} {:>11}", e[0], e[1], e[2], e[3], e[4]);
    }
    println!("seeds {first}..{}: generation, witnesses {generated:.1}s, sqleq {:.1}s", first + count, start.elapsed().as_secs_f64() - generated);
}

