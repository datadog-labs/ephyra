\echo A1 full minimal.sql shape, handler WHEN OTHERS (does the handler catch XX000?)
BEGIN;
CREATE DOMAIN d AS int2 CONSTRAINT d_k CHECK (VALUE IS NOT NULL);
ALTER TABLE t0 ALTER COLUMN c0 TYPE d;
ALTER DOMAIN d DROP CONSTRAINT d_k;
DO $$BEGIN ALTER DOMAIN d ADD CONSTRAINT d_k CHECK (VALUE >= -303); EXCEPTION WHEN OTHERS THEN RAISE NOTICE 'caught % %', SQLSTATE, SQLERRM; END$$;
