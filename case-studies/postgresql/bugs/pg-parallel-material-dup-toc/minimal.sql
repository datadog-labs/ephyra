CREATE TABLE p (a int) PARTITION BY LIST (a);
CREATE TABLE p1 PARTITION OF p FOR VALUES IN (1);
CREATE TABLE p2 PARTITION OF p FOR VALUES IN (2);
CREATE TABLE s (b int);
EXPLAIN (COSTS OFF) SELECT * FROM p WHERE a NOT IN (SELECT 1 FROM s, s s2);
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT * FROM p WHERE a NOT IN (SELECT 1 FROM s, s s2);
